def coverage(A=None):
    """운영규정 조문별로 사례·빈칸에 쓰인 횟수 — 다음 사례의 주제를 고를 때 아직 안 쓴 조문을 찾는다"""
    A = A or articles()
    used = {}
    for c in CASES:
        for s in c['stmts']:
            for art, _, _ in s['quotes']:
                used[art] = used.get(art, 0) + 1
        for b in c['blanks']:
            used[b['art']] = used.get(b['art'], 0) + 1
    return used


def workdays(start, n, holidays=(), weekend=(5, 6)):
    """start(YYYY-MM-DD) 부터 근무일 n일을 연속 사용할 때 날짜 목록. 제47조: 30일 미만이면 휴일(주말·공휴일)은 일수에 넣지 않는다.
    n >= 30 이면 달력일로 센다(연가를 뺀 휴가가 30일 이상 계속되면 산입)."""
    import datetime
    d = datetime.date.fromisoformat(start)
    hol = {datetime.date.fromisoformat(h) for h in holidays}
    out = []
    while len(out) < n:
        if n >= 30 or (d.weekday() not in weekend and d not in hol):
            out.append(d)
        d += datetime.timedelta(days=1)
    return out


