        for s in stm:
            for key in ('text', 'why', 'trap', 'quotes'):
                if not s.get(key):
                    errs.append(f"{c['id']} {s['k']}: {key} 없음")
            qs = []
            for art, quote, ref in s['quotes']:
                if art not in A:
                    errs.append(f"{c['id']} {s['k']}: 조문 키 없음 {art}"); continue
                body = norm(A[art]['text'] + A[art]['title'])
                if norm(quote) not in body:
                    errs.append(f"{c['id']} {s['k']}: 원문에 없는 인용 「{quote[:40]}」 ({art})")
                qs.append(f"{_cite(art, ref)} 「{quote}」")
            ex.append(f"<br><b>{s['k']} {s['v']}</b> {s['text']}<br>근거 " + '<br>근거 '.join(qs) +
                      f"<br>판단: {s['why']}" + (f"<br>계산: {s['calc']}" if s.get('calc') else '') + f"<br>함정: {s['trap']}")
        opts = ' '.join(f'{OPT[i]} {i + 1}개' for i in range(5))
